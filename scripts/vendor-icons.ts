import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

/**
 * Vendors Tabler outline icons for the shell (#71 PR 3) under the #72 rule. It reads a fixed list of
 * icon names from the installed exact devDependency, keeps only their <path> data and writes one ES
 * module exporting { name: string[] }. It never fetches anything.
 */
export const ICONS_PACKAGE = "@tabler/icons";
export const ICONS_VERSION = "3.50.0";
/** Tabler names the shell renders. Shell key names (src/contract.ts icon names) map onto these in shell/shell.js. */
export const ICON_NAMES = [
  "adjustments-horizontal", "alert-triangle", "arrow-right", "book-2", "box", "check", "external-link",
  "inbox", "plus", "search", "stack-2", "terminal-2", "user", "x",
] as const;
const sha256 = (value: string | Uint8Array) => createHash("sha256").update(value).digest("hex");
const BOUNDING_BOX = /^<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>$/;

export interface IconsManifest {
  schema: 1; name: typeof ICONS_PACKAGE; version: string; license: "MIT"; entry: "icons.js";
  sources: Record<string, { source: string; bytes: number; sha256: string }>;
  files: Record<string, { source: string; bytes: number; sha256: string }>;
}

/** The d attributes of one Tabler outline SVG, without the bounding-box path; throws on any other element. */
export function iconPaths(name: string, svg: string): string[] {
  const body = svg.replace(/^[\s\S]*?<svg\b[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const elements = body.match(/<[^>]+>/g) ?? [];
  if (body.replace(/<[^>]+>/g, "").trim() !== "") throw new Error(`${name}: unexpected text content`);
  const paths: string[] = [];
  for (const element of elements) {
    if (BOUNDING_BOX.test(element)) continue;
    const match = /^<path d="([^"<>]+)"\s*\/>$/.exec(element);
    if (!match) throw new Error(`${name}: only plain <path d> elements are allowed, found ${element}`);
    paths.push(match[1]!);
  }
  if (!paths.length) throw new Error(`${name}: no path data`);
  return paths;
}

function plan(repo: string, sourceDir?: string) {
  const pkg = JSON.parse(readFileSync(join(repo, "package.json"), "utf8")) as Record<string, Record<string, string> | undefined>;
  if (pkg.devDependencies?.[ICONS_PACKAGE] !== ICONS_VERSION) throw new Error(`package.json must pin devDependencies["${ICONS_PACKAGE}"] to ${ICONS_VERSION}`);
  for (const field of ["dependencies", "peerDependencies", "optionalDependencies"]) if (pkg[field]?.[ICONS_PACKAGE] !== undefined) throw new Error("Tabler icons must remain a build-time devDependency only");
  const root = sourceDir ?? join(repo, "node_modules", ...ICONS_PACKAGE.split("/"));
  const meta = JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as { name?: string; version?: string; license?: string };
  if (meta.name !== ICONS_PACKAGE || meta.version !== ICONS_VERSION || meta.license !== "MIT") throw new Error(`Expected installed ${ICONS_PACKAGE}@${ICONS_VERSION} with an MIT license; run bun install --frozen-lockfile`);
  const sources: IconsManifest["sources"] = {};
  const lines: string[] = [];
  for (const name of ICON_NAMES) {
    const source = `icons/outline/${name}.svg`;
    const svg = readFileSync(join(root, source));
    sources[name] = { source, bytes: svg.byteLength, sha256: sha256(svg) };
    lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(iconPaths(name, svg.toString("utf8")))},`);
  }
  const module = `// Generated by scripts/vendor-icons.ts from ${ICONS_PACKAGE} ${ICONS_VERSION} (MIT, see NOTICE). Do not edit.\nexport const ICONS = Object.freeze({\n${lines.join("\n")}\n});\n`;
  const license = readFileSync(join(root, "LICENSE"), "utf8");
  if (!license.includes("Permission is hereby granted") || !license.includes("THE SOFTWARE IS PROVIDED")) throw new Error("The upstream MIT LICENSE is missing or unexpected");
  const notice = `${ICONS_PACKAGE} ${ICONS_VERSION} (Tabler Icons, outline)\nSource: https://www.npmjs.com/package/${ICONS_PACKAGE}/v/${ICONS_VERSION}\nVendored: path data of ${ICON_NAMES.length} outline icons as icons.js\n\n${license}`;
  const manifest: IconsManifest = { schema: 1, name: ICONS_PACKAGE, version: ICONS_VERSION, license: "MIT", entry: "icons.js", sources, files: {
    "icons.js": { source: "icons/outline/*.svg", bytes: Buffer.byteLength(module), sha256: sha256(module) },
    NOTICE: { source: "LICENSE", bytes: Buffer.byteLength(notice), sha256: sha256(notice) },
  } };
  return { module, notice, manifest };
}

export function vendorIcons(options: { repoDir?: string; sourceDir?: string; outputDir?: string } = {}): IconsManifest {
  const repo = resolve(options.repoDir ?? join(import.meta.dir, ".."));
  const { module, notice, manifest } = plan(repo, options.sourceDir);
  const output = resolve(options.outputDir ?? join(repo, "shell", "vendor", "icons"));
  mkdirSync(output, { recursive: true });
  writeFileSync(join(output, "icons.js"), module);
  writeFileSync(join(output, "NOTICE"), notice);
  writeFileSync(join(output, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

/** Problems between the checked-in files, their manifest and (when installed) the pinned package. */
export function checkIcons(options: { repoDir?: string; outputDir?: string; requireInstalled?: boolean } = {}): string[] {
  const repo = resolve(options.repoDir ?? join(import.meta.dir, ".."));
  const output = resolve(options.outputDir ?? join(repo, "shell", "vendor", "icons"));
  const problems: string[] = [];
  let manifest: IconsManifest;
  try { manifest = JSON.parse(readFileSync(join(output, "manifest.json"), "utf8")) as IconsManifest; }
  catch { return [`${join(output, "manifest.json")} is missing or not JSON; run bun scripts/vendor-icons.ts`]; }
  if (manifest.name !== ICONS_PACKAGE || manifest.version !== ICONS_VERSION) problems.push(`manifest names ${manifest.name}@${manifest.version}, expected ${ICONS_PACKAGE}@${ICONS_VERSION}`);
  for (const [file, entry] of Object.entries(manifest.files ?? {})) {
    const path = join(output, file);
    if (!existsSync(path)) { problems.push(`${file} is listed in the manifest but missing`); continue; }
    const bytes = readFileSync(path);
    if (bytes.byteLength !== entry.bytes) problems.push(`${file}: ${bytes.byteLength} bytes, manifest says ${entry.bytes}`);
    if (sha256(bytes) !== entry.sha256) problems.push(`${file}: sha256 does not match the manifest`);
  }
  if (existsSync(join(repo, "node_modules", ...ICONS_PACKAGE.split("/"), "package.json"))) {
    try {
      if (JSON.stringify(plan(repo).manifest) !== JSON.stringify(manifest)) problems.push(`checked-in files differ from the installed ${ICONS_PACKAGE}@${ICONS_VERSION}; run bun scripts/vendor-icons.ts`);
    } catch (error) { problems.push(error instanceof Error ? error.message : String(error)); }
  } else if (options.requireInstalled) problems.push(`${ICONS_PACKAGE} is not installed; run bun install --frozen-lockfile`);
  return problems;
}

if (import.meta.main) {
  try {
    const args = process.argv.slice(2);
    if (args.some((a) => a !== "--check")) throw new Error("Usage: bun scripts/vendor-icons.ts [--check]");
    if (args.includes("--check")) {
      const problems = checkIcons({ requireInstalled: true });
      if (problems.length) { for (const p of problems) console.error(`vendor-icons: ${p}`); process.exitCode = 1; }
      else console.log("vendor-icons: ok");
    } else {
      const manifest = vendorIcons();
      console.log(`vendor-icons: ${manifest.name}@${manifest.version}, icons.js ${manifest.files["icons.js"]!.bytes} bytes`);
    }
  } catch (error) { console.error(`vendor-icons: ${error instanceof Error ? error.message : String(error)}`); process.exitCode = 1; }
}
